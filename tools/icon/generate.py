#!/usr/bin/env python3
"""Generate Phonon's launcher icon from an embedded pixel grid.

The mark is a thin rectangular frame around a 24x24 recycler. Run from the
repository root:

    python3 tools/icon/generate.py

Writes the adaptive foreground vector, the legacy mipmaps and the store icon.
No build step and no network: the grid is the source of truth.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/app/src/main/res"

GRID = [
    "...........######.......",
    ".......###########......",
    "......#############.....",
    ".....###############....",
    ".....######..#######....",
    ".....######..#######....",
    ".....#####....#####.....",
    "......####....#####.....",
    "....................##..",
    ".#####............#####.",
    ".######..........######.",
    ".######..........#######",
    "#######...........######",
    "######............######",
    ".####..............#####",
    ".####...............###.",
    "..#########...#########.",
    "..#########...########..",
    "....#######..#########..",
    "....#######..########...",
    "....#######...######....",
    ".....######...######....",
]

CYAN = (0, 229, 255, 255)
INK = (215, 227, 223, 255)
BLACK = (0, 0, 0, 255)


def cells():
    pts = {(x, y) for y, row in enumerate(GRID) for x, ch in enumerate(row) if ch == "#"}
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    w, h = x1 - x0 + 1, y1 - y0 + 1
    side = max(w, h)
    ox = (side - w) // 2
    oy = (side - h) // 2
    return {(x - x0 + ox, y - y0 + oy) for (x, y) in pts}, side


def runs(pts):
    rows = {}
    for x, y in pts:
        rows.setdefault(y, []).append(x)
    out = []
    for y, xs in rows.items():
        xs.sort()
        start = prev = xs[0]
        for x in xs[1:]:
            if x == prev + 1:
                prev = x
            else:
                out.append((start, y, prev + 1, y + 1)); start = prev = x
        out.append((start, y, prev + 1, y + 1))
    return out


def render(size, pts, side, glyph_fraction, inset, stroke):
    img = Image.new("RGBA", (size, size), BLACK)
    d = ImageDraw.Draw(img)
    i = inset * size
    d.rectangle([i, i, size - 1 - i, size - 1 - i], outline=INK, width=max(1, round(stroke * size)))
    g = glyph_fraction * size
    ox, oy, c = (size - g) / 2, (size - g) / 2, g / side
    for (x0, y0, x1, y1) in runs(pts):
        d.rectangle([ox + x0 * c, oy + y0 * c, ox + x1 * c - 0.5, oy + y1 * c - 0.5], fill=CYAN)
    return img


def round_mask(img):
    out = img.copy()
    mask = Image.new("L", img.size, 0)
    ImageDraw.Draw(mask).ellipse([0, 0, img.size[0] - 1, img.size[1] - 1], fill=255)
    out.putalpha(mask)
    return out


def vector(pts, side, viewport=108, inset=24.0, stroke=1.6, glyph_units=40.0):
    c = glyph_units / side
    o = (viewport - glyph_units) / 2
    glyph = " ".join(
        f"M{o + x0 * c:.2f},{o + y0 * c:.2f}h{(x1 - x0) * c:.2f}v{(y1 - y0) * c:.2f}h-{(x1 - x0) * c:.2f}z"
        for (x0, y0, x1, y1) in runs(pts)
    )
    a, b = inset, viewport - inset
    frame = (
        f"M{a},{a}h{b - a}v{b - a}h-{b - a}z "
        f"M{a + stroke},{a + stroke}h{b - a - 2 * stroke}v{b - a - 2 * stroke}"
        f"h-{b - a - 2 * stroke}z"
    )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/generate.py. The grid in that script is the source. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{viewport}dp"
    android:height="{viewport}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <path android:fillColor="#D7E3DF" android:fillType="evenOdd" android:pathData="{frame}" />
    <path android:fillColor="#00E5FF" android:pathData="{glyph}" />
</vector>
'''


def main():
    pts, side = cells()
    drawable = RES / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)
    (drawable / "ic_launcher_foreground.xml").write_text(vector(pts, side))

    sizes = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for bucket, px in sizes.items():
        d = RES / f"mipmap-{bucket}"
        d.mkdir(parents=True, exist_ok=True)
        art = render(px, pts, side, glyph_fraction=0.46, inset=0.14, stroke=0.011)
        art.save(d / "ic_launcher.png")
        round_mask(art).save(d / "ic_launcher_round.png")

    # legacy foreground png no longer used by the adaptive icon
    stale = RES / "mipmap-xxxhdpi/ic_launcher_foreground.png"
    if stale.exists():
        stale.unlink()

    store = ROOT / "fastlane/metadata/android/en-US/images"
    store.mkdir(parents=True, exist_ok=True)
    render(512, pts, side, glyph_fraction=0.46, inset=0.14, stroke=0.011).save(store / "icon.png")

    print(f"glyph {len(pts)} cells on a {side}x{side} grid; wrote vector, mipmaps and store icon")


if __name__ == "__main__":
    main()
